const assert = require('assert');
const fs = require('fs');
const path = require('path');
const {vendorsForView,productsForVendor} = require('../app/webpage/catalog.js');
const vendors=[{VendorID:'V1',BusinessName:'Same name'},{VendorID:'V2',BusinessName:'Same name'},{VendorID:'V3',BusinessName:'Other'}];
const matched=[{ProductID:'A',VendorID:'V1'},{ProductID:'C',VendorID:'V3'}];
assert.deepEqual(vendorsForView(matched,vendors,'customer',null,true),[vendors[0],vendors[2]]);
assert.deepEqual(vendorsForView([],vendors,'customer',null,false),vendors);
assert.deepEqual(vendorsForView([],vendors,'customer',null,true),[]);
assert.deepEqual(vendorsForView([],vendors,'vendor',vendors[1],true),[vendors[1]]);
assert.deepEqual(vendorsForView(matched,vendors,'vendor',vendors[0],false),[vendors[0]]);
assert.deepEqual(productsForVendor(matched,'V1'),[matched[0]]);
assert.deepEqual(productsForVendor(matched,'all'),matched);
assert.deepEqual(productsForVendor(matched,'V2'),[]);
const web=path.resolve(__dirname,'../app/webpage');
const normal=fs.readFileSync(path.join(web,'product.html'),'utf8');
const search=fs.readFileSync(path.join(web,'search_tag.html'),'utf8');
assert.equal(normal.replace(/<title>.*?<\/title>/,'<title>same</title>'),search.replace(/<title>.*?<\/title>/,'<title>same</title>'));
assert(normal.includes('catalog.css?v=20261105-compact-bar'));
assert(normal.includes('catalog.js?v=20261105-compact-bar'));
assert(search.includes('id="categoryMenu"'));
console.log('PASS: shared page markup/styles, relevant customer vendors, persistent own vendor, ID-based filtering and tag-scope preservation');
